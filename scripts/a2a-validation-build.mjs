import { readFileSync, writeFileSync } from "node:fs";
import { Ajv } from "ajv";
import standaloneCode from "ajv/dist/standalone/index.js";

// Official v0.3.0 bytes retained with the live audit; no schema from the CLI.
const schema = JSON.parse(readFileSync(new URL("../research/a2a-2026-09-06/official-schema-0.3.0.json", import.meta.url)));
const ajv = new Ajv({ strict: false, validateFormats: false, code: { source: true, esm: true } });
ajv.addSchema(schema, "a2a");
const validators = Object.fromEntries(["SendMessageRequest", "GetTaskRequest", "CancelTaskRequest"].map((name) => {
  ajv.addSchema({ $ref: `a2a#/definitions/${name}` }, name);
  return [`validate${name}`, name];
}));
const version = schema.definitions.AgentCard.properties.protocolVersion.default;
const output = "// Generated by scripts/a2a-validation-build.mjs from the official A2A 0.3.0 schema.\n" + `export const A2A_PROTOCOL_VERSION = ${JSON.stringify(version)};\n` + standaloneCode(ajv, validators) + "\n";
const target = new URL("../src/lib/a2a-validation.js", import.meta.url);
if (process.argv.includes("--check")) {
  if (readFileSync(target, "utf8") !== output) throw new Error("A2A validators differ from the versioned schema; run npm run a2a:validation:build");
} else writeFileSync(target, output);
