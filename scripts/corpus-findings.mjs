import { readFile, readdir, mkdir, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { createHash } from 'node:crypto';
import { buildCorpusViewer } from './lib/corpus-viewer.mjs';
import { deriveCorpusFindings } from './lib/corpus-findings.mjs';

const [inputDir, keyFile, outputDir] = process.argv.slice(2);
if (!inputDir || !keyFile || !outputDir) throw new Error('Usage: node scripts/corpus-findings.mjs SNAPSHOT_DIR PUBLIC_KEY_JSON OUTPUT_DIR');
const names = (await readdir(inputDir)).filter(n => /^[1-9]\d*\.json$/.test(n)).sort((a, b) => Number(a.split('.')[0]) - Number(b.split('.')[0]));
const buffers = await Promise.all(names.map(n => readFile(resolve(inputDir, n))));
const docs = buffers.map(b => JSON.parse(b.toString()));
const key = JSON.parse(await readFile(keyFile, 'utf8')).public_key;
if (!key) throw new Error('missing_public_verification_key');
// Reuse the existing verifier and chain-continuity guard; never analyze unauthenticated rows.
await buildCorpusViewer(docs, { base: 'https://scvd.store', publicKey: key });
const manifest = { public_key: key, authentication: 'Canonical digest, Ed25519 signature and contiguous previous-digest linkage passed. Bitcoin timestamps not checked.',
  inputs: docs.map((d, i) => ({ sequence: d.snapshot.sequence, digest: d.digest, file_sha256: createHash('sha256').update(buffers[i]).digest('hex'),
    source_url: `https://scvd.store/corpus/${d.snapshot.sequence}.json`, bytes: buffers[i].length })) };
await mkdir(outputDir, { recursive: true });
await writeFile(resolve(outputDir, 'corpus-inputs.json'), JSON.stringify(manifest, null, 2) + '\n');
const result = deriveCorpusFindings(docs);
await writeFile(resolve(outputDir, 'corpus-findings.json'), JSON.stringify(result, null, 2) + '\n');
const last = result.latest;
const eligible = result.pairs.filter(p => p.eligible_fresh_pairs > 0);
const lastPair = result.pairs.at(-1);
