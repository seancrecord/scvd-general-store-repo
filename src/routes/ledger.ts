/**
 * GET /ledger, /ledger/{week} and /ledger/{week}.json — one week of
 * everything this store observed, read as a research note rather than
 * shopped for across five tabs.
 *
 * THE ROOM EXISTS FOR A READER, not for an indexer. Every number here
 * is already public and already signed: the brief has served the
 * week's doors since S1, the changes feed has diffed week against week
 * since C6, and the corpus has held both since it shipped. What none
 * of them did was SAY ANYTHING. A reader wanting to know what happened
 * in a week had to open the brief for the counts, the changes feed for
 * the movement, /sources for whether the feeds were even answering,
 * /corrections for what we got wrong, and then do the joining
 * themselves — which is asking every reader to be an analyst.
 *
 * THE FINDINGS ARE MACHINE-DERIVED AND SAY SO. Every sentence in the
 * findings section is generated by a rule in services/week-ledger.ts
 * from fields it names in `derived_from`. That is a deliberate ceiling
 * on this page: it structures, it never interprets. The keeper's voice
 * is non-delegable and lives in the almanac, where a person writes it.
 *
 * PAGINATION IS BY SIGNED WEEK, and a week the chain does not hold is
 * a 404 that names the weeks it does (rule 52). Serving only the weeks
 * we looked would read as continuous coverage.
 */
