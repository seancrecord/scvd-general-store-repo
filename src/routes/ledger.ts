const KIND_LABEL: Record<LedgerFinding["kind"], string> = {
  finding: "Finding",
  gap: "Gap — ours",
  note: "Note",
};

function num(value: number): string {
  return value.toLocaleString("en-US");
}

function figure(n: string, label: string, of?: string): string {
  return `<div class="figure"><span class="n">${escapeHtml(n)}</span>${
    of ? `<span class="of">${escapeHtml(of)}</span>` : ""
  }<span class="label">${escapeHtml(label)}</span></div>`;
}

function findingHtml(finding: LedgerFinding): string {
  return `<div class="finding kind-${escapeHtml(finding.kind)}">
    <span class="kind">${escapeHtml(KIND_LABEL[finding.kind])}</span>
    <p class="headline">${escapeHtml(finding.headline)}</p>
    <p class="detail">${escapeHtml(finding.detail)}</p>
    <span class="from">Derived from ${finding.derived_from
      .map((field) => `<code>${escapeHtml(field)}</code>`)
      .join(", ")}</span>
  </div>`;
}

function movementHtml(ledger: WeekLedger): string {
  const changes = ledger.changes;
  if (!changes) {
    return `<p class="menu-desc">No previous signed week to compare against, so
    there is no movement section. This is the first week the chain holds, or the
    week before it is one of the gaps named below.</p>`;
  }
  const rows: [string, number][] = [
    ["Appeared — named by a feed for the first time", changes.additions.length],
    ["Left — named by no feed this week", changes.removals.length],
    ["Recovered — payable again after not being", changes.recoveries.length],
    ["Regressed — was payable, is not", changes.regressions.length],
    ["Changed payment route", changes.changed_payment_routes.length],
    ["Changed price", changes.changed_prices.length],
    ["Changed defect state", changes.changed_defect_state.length],
  ];
  return `<table class="movement">
    <thead><tr><th>Against ${escapeHtml(changes.previous?.week ?? "—")}</th><th class="n">doors</th></tr></thead>
    <tbody>${rows
      .map(([label, count]) => `<tr><td>${escapeHtml(label)}</td><td class="n">${num(count)}</td></tr>`)
      .join("")}</tbody>
  </table>
  <p class="menu-meta">Denominators, because a movement count without them is
  a rate in disguise: ${num(changes.hosts_in_week)} doors this week,
  ${num(changes.hosts_in_previous)} last week, ${num(changes.hosts_in_both)} in both.</p>`;
}

function renderLedger(ledger: WeekLedger, base: string): string {
  const { brief } = ledger;
  const answered = brief.doors.payable + brief.doors.not_payable;
  const gaps = ledger.findings.filter((f) => f.kind === "gap");
  const rest = ledger.findings.filter((f) => f.kind !== "gap");

  const nav = `<div class="weekbar">
    ${
      ledger.previous_week
        ? `<a href="/ledger/${escapeHtml(ledger.previous_week)}">← ${escapeHtml(ledger.previous_week)}</a>`
        : `<span class="menu-meta">← no earlier week</span>`
    }
    <span class="spacer"></span>
    <span class="menu-meta">Sealed ${escapeHtml(ledger.taken_at)} · entry ${escapeHtml(String(ledger.sequence))}</span>
    <span class="spacer"></span>
    ${
      ledger.next_week
        ? `<a href="/ledger/${escapeHtml(ledger.next_week)}">${escapeHtml(ledger.next_week)} →</a>`
        : `<span class="menu-meta">no later week →</span>`
    }
  </div>`;

  const corrections = ledger.corrections_this_week.length
    ? `<section><h2>What we got wrong, this week</h2>
      ${ledger.corrections_this_week
        .map(
          (correction) => `<div class="finding kind-gap">
        <span class="kind">Correction · ${escapeHtml(correction.date)}</span>
        <p class="detail">${escapeHtml(correction.what_was_wrong)}</p>
        <span class="from">${escapeHtml(correction.how_long)}</span>
      </div>`,
        )
        .join("")}
      <p class="menu-meta">The full record, all of it, is at
      <a href="/corrections">/corrections</a>.</p></section>`
    : "";

  return `<section>
    <p class="standfirst">${escapeHtml(LEDGER_PROPOSITION)}</p>
    <p class="menu-desc">This is one week of the public x402 neighbourhood as
    this store's weekly round saw it — what we reached, what answered, what
    broke, what moved, and the part that matters most on a page like this:
    what we could not see. Every figure is a count over a single signed,
    hash-chained snapshot, and every sentence names the fields it came from.</p>
    ${nav}
  </section>

  <section><h2>The week in figures</h2>
  <div class="figures">
    ${figure(num(brief.doors.listed), "doors named by our feeds")}
    ${figure(num(brief.doors.probed), "knocked on", `of ${num(brief.doors.listed)} named`)}
    ${figure(num(brief.doors.payable), "a buyer could pay", answered ? `of ${num(answered)} that answered` : undefined)}
    ${figure(num(brief.doors.not_payable), "answered, not payable", answered ? `of ${num(answered)} that answered` : undefined)}
    ${figure(num(brief.doors.unreachable), "did not answer")}
    ${figure(num(brief.doors.offers_seen), "carried a parseable offer")}
  </div>
  <p class="menu-meta">Counts, each with the denominator it belongs to. No
  figure on this page is taken over the doors we did not knock on.</p>
  </section>

  <section><h2>Findings</h2>
  <p class="menu-desc">Generated from the week's own fields by a fixed rule,
  the same rule on every week. Structure, not interpretation — nothing here
  is a judgement about an operator, and nothing here is anybody's opinion.</p>
  ${rest.map(findingHtml).join("")}
  </section>

  <section><h2>What we could not see</h2>
  <p class="menu-desc">Counted against the instrument, on the same page as the
  findings, because a week's reading is exactly where a reader is most likely
  to mistake what we saw for what happened.</p>
  ${
    gaps.length
      ? gaps.map(findingHtml).join("")
      : `<p class="menu-desc">No gap fired this week: every named door was
      knocked on, our vantage held on every probe, the round did not flag its
      own coverage, every source answered, and the chain holds every week
      behind this one. Stated rather than omitted — a section that disappears
      when it is empty teaches a reader to read silence as completeness.</p>`
  }
  </section>

  <section><h2>What moved</h2>${movementHtml(ledger)}</section>

  ${
    brief.defects.length
      ? `<section><h2>Defects, by name</h2>
    <table class="movement">
      <thead><tr><th>defect</th><th class="n">doors</th></tr></thead>
      <tbody>${brief.defects
        .map(
          (defect) =>
            `<tr><td>${escapeHtml(defect.title)} <code>${escapeHtml(defect.id)}</code></td><td class="n">${num(defect.count)}</td></tr>`,
        )
        .join("")}</tbody>
    </table>
    <p class="menu-meta">A defect is a named check that failed, from the
    published vocabulary at <a href="/defects">/defects</a>. One door can carry
    several. A failure is a fact about one artifact at one moment, never a
    standing verdict on whoever runs it.</p></section>`
      : ""
  }

  <section><h2>Were the feeds answering?</h2>
  <p class="menu-desc">${num(ledger.sources.live)} live,
  ${num(ledger.sources.stale)} stale, ${num(ledger.sources.never_answered)}
  never answered, ${num(ledger.sources.unread)} named but not read.
  ${
    ledger.sources.not_answering.length
      ? `Quiet right now: ${escapeHtml(ledger.sources.not_answering.join(", "))}.`
      : "All of them, at the time this page was derived."
  }</p>
  <p class="menu-meta">Source liveness is derived from run history rather than
  maintained by hand, and is current as of this request, not as of the sealed
  week — the full register is at <a href="/sources">/sources</a>.</p>
  </section>

  ${corrections}

  <section class="methods">
    <h3>How to redo every number on this page</h3>
    <p class="menu-desc">${escapeHtml(ledger.how_to_rederive)}</p>
    <h3>What this is not</h3>
    <p class="menu-desc">${escapeHtml(ledger.what_this_is_not)}</p>
    <h3>What this costs</h3>
    <p class="menu-desc">${escapeHtml(LEDGER_FOR_MONEY)}</p>
    <p class="menu-meta">${escapeHtml(LEDGER_FREE_FIRST)}</p>
    <p class="menu-meta">The same ledger as JSON:
    <a href="/ledger/${escapeHtml(ledger.week)}.json"><code>${escapeHtml(base)}/ledger/${escapeHtml(ledger.week)}.json</code></a>.
    The signed snapshot behind it:
    <a href="/corpus/${escapeHtml(String(ledger.sequence))}.json"><code>/corpus/${escapeHtml(String(ledger.sequence))}.json</code></a>.
    Every door, alphabetical: <a href="/doors">/doors</a>.
    Where these numbers come from: <a href="/sources">/sources</a>.</p>
  </section>
  ${nav}
  ${jsonLdScript({
    "@context": "https://schema.org",
    "@type": "Report",
    name: `The Week's Ledger — ${ledger.week}`,
    description: LEDGER_PROPOSITION,
    url: `${base}/ledger/${ledger.week}`,
    creator: organizationRef(base),
    isAccessibleForFree: true,
    datePublished: ledger.taken_at,
    temporalCoverage: ledger.week,
    citation: `${base}/corpus/${ledger.sequence}.json`,
    license: "https://creativecommons.org/licenses/by/4.0/",
  })}`;
}

/**
 * THE FIVE ANSWERS (60.4) and the three sentences (60.2), on the index
 * twin and on every week's twin alike. A reader who lands on one week
 * should not have to walk up to the index to learn what the room is
 * or what it costs.
 */
function fiveAnswers(base: string) {
  return {
    what_this_is: LEDGER_PROPOSITION,
    proposition: LEDGER_PROPOSITION,
    price: LEDGER_FOR_MONEY,
    free_first: LEDGER_FREE_FIRST,
    opened: INSTRUMENTS_OPENED,
    how_to_call: {
      the_index: `GET ${base}/ledger for every week the chain holds, HTML or JSON by Accept.`,
      one_week: `GET ${base}/ledger/2026-W36 for the page, or ${base}/ledger/2026-W36.json for the same reading as JSON.`,
      the_findings: "Every entry in `findings` names the fields it was computed from in `derived_from`; fetch the snapshot it cites and recount.",
      subscribe: `The signed source is ${base}/corpus/latest.json, which carries ETag and Last-Modified for a conditional GET.`,
    },
    errors: {
      unknown_week: "A week the chain does not hold answers 404 with `known_weeks` naming the weeks it does. This store does not invent a baseline for a week it did not seal.",
      malformed_week: "Anything that is not a YYYY-Wnn week answers 404 rather than being guessed at.",
      no_weeks_yet: "With an empty chain the index answers 200 with an empty `weeks_held`. That is our age, not an error.",
    },
    security: securityBlock(base, {
      does_in_your_name: "Nothing. A GET here reads signed snapshots already published; no door is probed and nothing is fetched from anyone on your behalf.",
      stores: "Nothing about you. The porch counts a visit by surface, never by caller.",
    }),
  };
}

function notFound(week: string, known: string[], base: string) {
  return {
    error: `The chain holds no signed week named ${week}. This store does not invent a baseline for a week it did not seal.`,
    known_weeks: known,
    index: `${base}/ledger`,
  };
}

async function loadLedger(env: HonoEnv["Bindings"], week?: string) {
  const [records, register] = await Promise.all([
    listCorpus(env),
    sourceRegister(env).catch(() => null),
  ]);
  return deriveLedger(records, env.STORE_BASE_URL, register, week);
}

/** The index: every week the chain holds, newest first. */
